def length_text(value):
    """`16`, `2.5`: a length as the rows name it."""
    return f"{float(value):g}"


def wurth_number(key):
    """Würth's article key (`00846  8`) in its groups (`0084 6 8`)."""
    groups = [key[:4], key[4:7].strip(), key[7:].strip()]
    return " ".join(g for g in groups if g)


def part_number(supplier, raw):
    return wurth_number(raw) if supplier == "wurth" else raw


def page_url(supplier, page):
    return (WURTH_PAGES if supplier == "wurth" else ETRA_PAGES) + page


def screw_articles():
    """Every screw article: (component, size, head, length, supplier,
    material, finish, part number, page), head "ISO" or "DIN" (the DIN
    933 head of its size)."""
    out = []
    for component, supplier, material, finish, page, text in SCREWS:
        for line in text.strip().splitlines():
            line = line.strip()
            verbatim = re.fullmatch(r"(M[\d.]+)(/DIN)?\s*=\s*(.+)", line)
            if verbatim:
                size, din, pairs = verbatim.groups()
                entries = [pair.split(":") for pair in pairs.split()]
            else:
                match = re.fullmatch(r'(M[\d.]+)(/DIN)?\s+"([^"]*)"\s*:\s*([\d.,]+)', line)
                if not match:
                    raise ValueError(f"{component} {supplier} {page}: cannot read {line!r}")
                size, din, prefix, lengths = match.groups()
                width = 3 if supplier == "etra" else 0
                entries = [(length, prefix + length.zfill(width)) for length in lengths.split(",")]
            for length, raw in entries:
                out.append((component, size, "DIN" if din else "ISO", length_text(length), supplier, material,
                            finish, part_number(supplier, raw), page))
    return out


def sized_articles():
    """Every nut and washer article: (component, size, standard, supplier,
    material, finish, part number, page)."""
    out = []
    for component, standard, supplier, material, finish, page, text in SIZED:
        for pair in text.split():
            size, raw = pair.split("=")
            out.append((component, size, standard, supplier, material, finish, part_number(supplier, raw), page))
    return out
