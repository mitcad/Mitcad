// Port patch 0260: a contour carried on across a small notch in the rim it
// rounds onto the next edge of that rim
// (BRepFilletAPI_MakeFillet::CarryChainsAcrossNotches, called after the
// contours are added). OCCT ended the contour at the notch, its end cut by
// the notch's face, and the next arc stayed sharp (the result invalid).
//
// test_fillet_results.cpp carries a rounding of 0.3 across a notch 0.1
// deep in a disc's rim. Here the notch of the patch's case: a tapered notch
// 0.25 deep and 0.57 wide at the rim of a D (a disc of radius 20 cut by the
// plane y = 12), its three top edges 0.28 to 0.31 long; the arc on one side
// given and rounded with 0.5: the arc beyond the notch is added as a
// contour of its own, the two meet over the notch (0241): built, valid,
// the body the one with both arcs given and the one with the D's whole rim
// rounded and the notch cut after, a torus face generated by the given
// edge. The boundary: a notch 2 wide (wider than the ball): nothing is
// carried, the contours stay as given, as stock.
//
// The call is the patch's: without the patch it does not exist, and the
// test takes it for one that carries nothing.

#include <type_traits>
#include <utility>
#include <vector>

#include <BRepAdaptor_Surface.hxx>
#include <BRepAlgoAPI_Cut.hxx>
#include <BRepBuilderAPI_MakeFace.hxx>
#include <BRepBuilderAPI_MakePolygon.hxx>
#include <BRepPrimAPI_MakeBox.hxx>
#include <BRepPrimAPI_MakeCylinder.hxx>
#include <BRepPrimAPI_MakePrism.hxx>
#include <gp_Ax2.hxx>
#include <gp_Dir.hxx>
#include <gp_Vec.hxx>

#include "port_test.hpp"

namespace {

// Whether the maker has the patch's CarryChainsAcrossNotches.
template <typename Maker, typename = void>
struct CanCarry : std::false_type {};

template <typename Maker>
struct CanCarry<Maker, std::void_t<decltype(std::declval<Maker&>().CarryChainsAcrossNotches())>> : std::true_type {};

// The contours the maker carries across notches; -1 without the patch.
template <typename Maker>
int carried_across_notches(Maker& maker) {
  if constexpr (CanCarry<Maker>::value) {
    return maker.CarryChainsAcrossNotches();
  } else {
    (void)maker;
    return -1;
  }
}

// The edge of a shape whose middle lies nearest to p.
TopoDS_Edge nearest_edge(const TopoDS_Shape& shape, const gp_Pnt& p) {
  TopoDS_Edge best;
  double      nearest = 1e100;
  for (TopExp_Explorer e(shape, TopAbs_EDGE); e.More(); e.Next()) {
    const TopoDS_Edge&            candidate = TopoDS::Edge(e.Current());
    double                        first = 0.0, last = 0.0;
    const occ::handle<Geom_Curve> curve = BRep_Tool::Curve(candidate, first, last);
    if (curve.IsNull()) {
      continue;
    }
    const double d = curve->Value(0.5 * (first + last)).Distance(p);
    if (d < nearest) {
      nearest = d;
      best    = candidate;
    }
  }
  return best;
}

int torus_faces(const TopoDS_Shape& shape) {
  int n = 0;
  for (TopExp_Explorer f(shape, TopAbs_FACE); f.More(); f.Next()) {
    n += BRepAdaptor_Surface(TopoDS::Face(f.Current())).GetType() == GeomAbs_Torus ? 1 : 0;
  }
  return n;
}

// The point of the circle of radius 20 at the angle (degrees), on the top.
gp_Pnt on_rim(double degrees) {
  const double a = degrees * test::kPi / 180.0;
  return gp_Pnt(20.0 * std::cos(a), 20.0 * std::sin(a), 5.0);
}

// A disc of radius 20, 5 high, cut by the plane y = 12: its top's rim an
// arc from (16, 12) round through the bottom to (-16, 12), the
// cylinder's seam at (20, 0) on the arc right of the notch.
TopoDS_Shape d_shape() {
  const TopoDS_Shape disc =
    BRepPrimAPI_MakeCylinder(gp_Ax2(gp_Pnt(0, 0, 0), gp_Dir(0, 0, 1), gp_Dir(1, 0, 0)), 20, 5).Shape();
  return BRepAlgoAPI_Cut(disc, BRepPrimAPI_MakeBox(gp_Pnt(-25, 12, -1), gp_Pnt(25, 25, 6)).Shape()).Shape();
}

// A tapered notch through the D's rim at its bottom (y = -20), 0.25 deep:
// `bottom` wide at its bottom, 0.26 wider at the rim (its sides 0.28 long
// on the top).
TopoDS_Shape notch(double bottom) {
  const double               b = 0.5 * bottom, out = b + 0.13 * 0.85 / 0.25;
  BRepBuilderAPI_MakePolygon polygon;
  for (const auto& [x, y] :
       std::vector<std::pair<double, double>>{{out, -20.6}, {b, -19.75}, {-b, -19.75}, {-out, -20.6}}) {
    polygon.Add(gp_Pnt(x, y, -1));
  }
  polygon.Close();
  const TopoDS_Face face = BRepBuilderAPI_MakeFace(polygon.Wire(), true).Face();
  return BRepPrimAPI_MakePrism(face, gp_Vec(0, 0, 7)).Shape();
}

// The notch 0.57 wide at the rim (0.31 at its bottom): the left arc's
// rounding of 0.5 is carried onto the right arc.
void test_rounding_of_0_5_carried_across_a_notch_0_57_wide() {
  const TopoDS_Shape d    = d_shape();
  const TopoDS_Shape body = BRepAlgoAPI_Cut(d, notch(0.31)).Shape();
  CHECK(port::valid(body));
  const TopoDS_Edge        given = nearest_edge(body, on_rim(206.6));
  BRepFilletAPI_MakeFillet carried(body);
  carried.Add(0.5, given);
  CHECK(carried_across_notches(carried) == 1);
  CHECK(carried.NbContours() == 2);
  const TopoDS_Shape result = port::built(carried, "carried");
  CHECK(port::valid(result));
  const TopoDS_Shape both  = port::rounded(body, {given, nearest_edge(body, on_rim(315))}, 0.5);
  const TopoDS_Shape whole = port::rounded(d, {nearest_edge(d, on_rim(250))}, 0.5);
  CHECK(port::valid(both));
  CHECK(port::valid(whole));
  if (!port::valid(result) || !port::valid(both) || !port::valid(whole)) {
    return;
  }
  const TopoDS_Shape expected = BRepAlgoAPI_Cut(whole, notch(0.31)).Shape();
  CHECK_NEAR_TOL(port::volume_of(result), port::volume_of(expected), 1e-7);
  CHECK_NEAR_TOL(port::volume_of(result), port::volume_of(both), 1e-8);
  CHECK(port::count_of(result, TopAbs_FACE) == port::count_of(both, TopAbs_FACE));
  CHECK(torus_faces(result) == torus_faces(both));
  int given_tori = 0;
  for (const TopoDS_Shape& f : carried.Generated(given)) {
    given_tori +=
      f.ShapeType() == TopAbs_FACE && BRepAdaptor_Surface(TopoDS::Face(f)).GetType() == GeomAbs_Torus ? 1 : 0;
  }
  CHECK(given_tori >= 1);
}

// The boundary: the notch 2 wide at the rim (1.74 at its bottom), wider
// than the ball: nothing is carried, the contour stays the one given.
void test_nothing_carried_across_a_notch_wider_than_the_ball() {
  const TopoDS_Shape body = BRepAlgoAPI_Cut(d_shape(), notch(1.74)).Shape();
  CHECK(port::valid(body));
  BRepFilletAPI_MakeFillet narrow(body);
  narrow.Add(0.5, nearest_edge(body, on_rim(206.6)));
  CHECK(carried_across_notches(narrow) <= 0);
  CHECK(narrow.NbContours() == 1);
}

} // namespace

MITCAD_PORT_TEST("0260", test_rounding_of_0_5_carried_across_a_notch_0_57_wide);
MITCAD_PORT_TEST("0260", test_nothing_carried_across_a_notch_wider_than_the_ball);
