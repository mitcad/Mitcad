#pragma once

#include <functional>
#include <vector>

#include <QHash>
#include <QRegularExpression>
#include <QString>
#include <QStringList>

namespace mitcad {

// The model's messages in the interface language (mitcad#1284,
// docs/translations.md "The model's messages"). The model (Rust, core/)
// writes its refusals, errors, warnings and notes in English, and the JSON
// API, MCP and the command line keep them so: agents and scripts read them.
// What the application shows the user is translated here, as it is shown.
//
// A message's id is its template: the English text of the Rust source with
// its values as %1, %2, ... ("feature %1 does not exist"), as Qt names a
// text by its English source. Every template of core/ is listed in
// kModelMessageTemplates (ModelMessageTemplates.cpp, generated by
// `mitcad-translations messages`) and translated in the context
// ModelMessage of the catalogues. A message is matched against the
// templates (the one with the most fixed text wins), its values taken from
// it, each value that is itself a message translated in turn, and put into
// the translated template; the values (names, numbers with units,
// references) stay as they are. A message without a template, or whose
// template the catalogue has not translated, stays English.

// The generated list (ModelMessageTemplates.cpp).
extern const char* const kModelMessageTemplates[];
extern const int kModelMessageTemplateCount;

// A message matched to its template: the template's index and its values.
struct ModelMessageMatch {
  int index = -1;
  QStringList values;
  bool found() const { return index >= 0; }
};

// Matching messages against a list of templates; the application's uses
// kModelMessageTemplates, the tests their own.
class ModelMessageCatalogue {
public:
  ModelMessageCatalogue(const char* const* templates, int count);

  int size() const { return static_cast<int>(m_templates.size()); }
  const char* source(int index) const { return m_templates[static_cast<std::size_t>(index)].source; }

  // The template `message` is (the whole of it), and its values.
  ModelMessageMatch match(const QString& message) const;

  // `message` with `translated(source)` of its template, its values
  // translated in turn (to `depth` levels); a template `translated` gives
  // back unchanged (or empty) keeps the whole message English. A message
  // that is no template is translated line by line, and after a lead-in
  // that ends in ": " (an application's "Could not export: <message>").
  // `untranslated` is set when a part of it stayed English.
  using Translate = std::function<QString(const char* source)>;
  QString translate(const QString& message, const Translate& translated, bool* untranslated = nullptr) const;

private:
  struct Template {
    const char* source = nullptr;
    QRegularExpression pattern;
    int fixed = 0; // its length without the placeholders
  };
  QString translateWhole(const QString& message, const Translate& translated, int depth, bool* matched) const;

  std::vector<Template> m_templates;
  // Templates by a word of their fixed text (the rarest one each has);
  // those without one are tried for every message.
  QHash<QString, std::vector<int>> m_byWord;
  std::vector<int> m_everywhere;
};

// `text` with %1, %2, ... (up to %99) replaced by `values`; a placeholder
// without a value stays as it is.
QString fillTemplate(const QString& text, const QStringList& values);

// A message of the model as the user sees it, in the interface language
// (the text itself in English). With MITCAD_LOG_UNTRANSLATED=1 a message
// that stays English in another language is logged once:
// `Untranslated model message: <text>`.
QString modelMessage(const QString& english);
QString modelMessage(const char* english);
QStringList modelMessages(const QStringList& english);

} // namespace mitcad
